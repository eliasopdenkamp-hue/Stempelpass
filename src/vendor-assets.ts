/**
 * Static client-side decoder asset for the staff camera scan.
 *
 * @zxing/library (Apache-2.0) UMD bundle, served at GET /vendor/zxing.min.js
 * and lazy-loaded by the staff scan script ONLY on browsers without a native
 * BarcodeDetector (iOS Safari, Firefox, desktop Chrome — Android Chrome and
 * desktop Chrome-with-flag use the built-in detector and never download this).
 * It decodes Code-128 (the Google Wallet card barcode) and QR (the webcard
 * code QR) entirely in the browser — no image ever leaves the device.
 *
 * PACKAGING (PR #45, fix for the PR #44 cold-start crash): the minified bundle
 * is NOT read from node_modules at runtime anymore. PR #44 loaded it at
 * runtime from node_modules via readFileSync on a require-resolve'd path into
 * the @zxing umd directory; the @vercel/nft tracer did not copy that file
 * into the serverless function bundle (the path string only appeared in
 * source, never in a real import), so the deployed function threw ENOENT on
 * module load and EVERY route answered FUNCTION_INVOCATION_FAILED. The UMD is
 * now embedded build-time as base64 in src/vendor/zxing-umd.ts (generated by
 * scripts/embed-zxing.ts, committed, deterministic) and decoded ONCE here at
 * module load into memory — no fs, no node_modules access at runtime, no
 * package tracing involved. The deploy checklist runs `bun run verify-bundle`
 * after `vercel build --prod`, which proves the exact original bytes are
 * present inside the BUILT function bundle (decode + sha256 compare) and that
 * no runtime-fs probe of the @zxing package path remains.
 */
import { ZXING_UMD_BASE64 } from './vendor/zxing-umd.js';

/** Decoded once at module load; served from memory. */
const ZXING_SOURCE = Buffer.from(ZXING_UMD_BASE64, 'base64').toString('utf8');

/** GET /vendor/zxing.min.js — public, no auth, no DB, immutable 1 h cache. */
export function vendorZxingResponse(): Response {
  return new Response(ZXING_SOURCE, {
    headers: {
      'Content-Type': 'application/javascript; charset=utf-8',
      'Cache-Control': 'public, max-age=3600',
      'X-Content-Type-Options': 'nosniff',
    },
  });
}

/** The exact decoded asset text (exported for exact-identity tests). */
export function zxingSource(): string {
  return ZXING_SOURCE;
}

/** Exposed for the unit test (embedded payload decodes, non-empty, UMD hook). */
export function zxingSourceStats(): { bytes: number; hasGlobal: boolean } {
  return { bytes: Buffer.byteLength(ZXING_SOURCE, 'utf8'), hasGlobal: ZXING_SOURCE.includes('ZXing') };
}