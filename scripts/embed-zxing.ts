/**
 * Embed @zxing/library UMD into the repo as a TS module (build-time asset).
 *
 * WHY: PR #44 loaded the client-side decoder at runtime via
 * `readFileSync(require.resolve('@zxing/library/umd/index.min.js'))`. The
 * @vercel/nft tracer did NOT copy that file into the serverless function
 * bundle (the string only appeared in source/comments, never in a real
 * import), so production crashed on cold start with FUNCTION_INVOCATION_FAILED
 * on ALL routes. This script eliminates the runtime fs dependency: it reads
 * the UMD once HERE (at build/commit time), base64-encodes it and writes
 * `src/vendor/zxing-umd.ts`. The serverless function then carries the full
 * payload inside its own bundled JS — decode happens in-memory at module
 * load, zero node_modules access at runtime.
 *
 * base64 is used (not a JS string literal with escaped quotes/backslashes)
 * because it is byte-exact for arbitrary content and needs no escaping.
 *
 * Usage:  bun run embed-zxing            (after upgrading @zxing/library)
 * Output: src/vendor/zxing-umd.ts        (committed, deterministic)
 *
 * The generated file is verified against this original by
 * `bun run verify-bundle` (built function output) and by the unit suite
 * (tests/staff-scan.test.ts — sha256 of the decoded constant must equal
 * ZXING_UMD_SHA256).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const UMD_REL = 'node_modules/@zxing/library/umd/index.min.js';
const OUT_REL = 'src/vendor/zxing-umd.ts';

const raw = readFileSync(join(ROOT, UMD_REL));
const base64 = raw.toString('base64');
const sha256 = createHash('sha256').update(raw).digest('hex');
const pkg = JSON.parse(
  readFileSync(join(ROOT, 'node_modules/@zxing/library/package.json'), 'utf8'),
) as { version?: string; license?: string };

const header = `/**
 * AUTO-GENERATED by scripts/embed-zxing.ts — DO NOT EDIT BY HAND.
 * Regenerate with \`bun run embed-zxing\` after upgrading @zxing/library.
 *
 * Original asset : ${UMD_REL}
 * Package version: ${pkg.version ?? 'unknown'}
 * License        : ${pkg.license ?? 'unknown'} (see node_modules/@zxing/library)
 * Byte size      : ${raw.length}
 * SHA-256        : ${sha256}
 *
 * The minified UMD bundle is stored here as base64 so the production
 * serverless function carries the client-side decoder WITHOUT any runtime
 * readFileSync/require.resolve on node_modules. The @vercel/nft trace missed
 * the require.resolve'd asset in PR #44 (FUNCTION_INVOCATION_FAILED on cold
 * start); src/vendor-assets.ts now decodes this constant once at module load.
 */

/** Original byte size of ${UMD_REL}. */
export const ZXING_UMD_BYTES = ${raw.length};

/** SHA-256 of the original bytes (pinned here; verify-bundle compares against it). */
export const ZXING_UMD_SHA256 = '${sha256}';

/** base64 of the original bytes; decode with Buffer.from(v, 'base64'). */
export const ZXING_UMD_BASE64 =\n  '${base64}';
`;

writeFileSync(join(ROOT, OUT_REL), header);
console.log(
  JSON.stringify(
    {
      ok: true,
      input: UMD_REL,
      output: OUT_REL,
      bytes: raw.length,
      sha256,
      base64Chars: base64.length,
      version: pkg.version ?? null,
    },
    null,
    2,
  ),
);